<?php

$a = 5;
$b = 10;

$sum = $a + $b;  // сложение
echo "$a + $b = $sum";

$difference = $a - $b; // разность
echo "$a - $b = $difference";

$multiplication = $a * $b; // умножение
echo "$a * $b = $multiplication";

$division = $a / $b; // Деление
echo "$a / $b = $division";

$remains = $a % $b; // Остаток от деления
echo "$a % $b = $remains";

